# ============================================================================
# МАСШТАБЫ ДЛЯ LOSS-ФУНКЦИИ
# ============================================================================
# Координаты задаются в метрах, ETA - в секундах. Без нормализации
# в loss-функции получаются значения ~10^6 для координат и ~10^7 для ETA,
# что приводит к катастрофическому дисбалансу градиентов:
# классификационный loss (~ ln(15) ~ 2.7) полностью теряется на фоне.
# Введённые константы используются ТОЛЬКО внутри loss-функции -
# метрики ADE/FDE/MAE_ETA по-прежнему вычисляются в метрах и секундах.

# Масштаб координат для Huber loss (м). Типичный радиус зоны полётов
# ~10 км; при делении (pred-target) / COORD_SCALE Huber loss получается
# порядка единицы вместо 10^5.
COORD_SCALE = 1000.0

# Масштаб ETA для MSE (с). Типичные ETA = 1000-7000 с;
# нормированный MSE получается порядка единиц.
ETA_SCALE = 1000.0

# Максимальная коррекция к baseline-у линейной экстраполяции (м).
# Декодер реализует prior: next_point = prev + last_velocity * dt + correction,
# где correction = tanh(raw) * MAX_DELTA_CORRECTION_PER_STEP.
# Baseline = "продолжай движение со скоростью последней наблюдаемой точки"
# уже даёт физически разумный прогноз и устраняет локальный минимум на нуле,
# в котором декодер раньше застревал. Коррекция нужна для манёвров:
# повороты, замедление при подходе к цели, ускорение и т.п.
# 500 м/шаг с запасом покрывает физически возможные изменения скорости
# (типичная скорость БПЛА 30-60 м/с, шаг 1 с).
MAX_DELTA_CORRECTION_PER_STEP = 500.0

# Шаг времени между точками траектории (с). Используется декодером
# при вычислении linear baseline = last_velocity * dt. Должно совпадать
