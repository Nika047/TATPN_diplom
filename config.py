# L = alpha * L_trajectory + beta * L_target + gamma * L_eta
LOSS_ALPHA = 1.0     # Вес Huber loss для траектории
LOSS_BETA = 1.0      # Вес CrossEntropy для классификации цели
LOSS_GAMMA = 0.5     # Вес MSE для предсказания ETA (времени до цели)

